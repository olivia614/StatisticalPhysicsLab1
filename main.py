def part_distributions(macros: MacroWriter) -> None:
    ns = (20, 50, 80, 100)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.2, 3.0))
    for n in ns:
        k = np.arange(n + 1)
        omega = np.array(cb.multiplicity_row(n), dtype=float)
        ax1.semilogy(k, omega, ".-", ms=3, lw=0.8, label=f"$N={n}$")
        ax2.plot(k, omega / 2.0**n, ".-", ms=3, lw=0.8, label=f"$N={n}$")
    ax1.set_xlabel("Number of heads $k$")
    ax1.set_ylabel(r"Multiplicity $\Omega(N,k)$")
    ax1.set_title("(a)", loc="left")
    ax2.set_xlabel("Number of heads $k$")
    ax2.set_ylabel(r"Probability $P_k=\Omega(N,k)/2^N$")
    ax2.set_title("(b)", loc="left")
    ax2.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "fig_distributions.pdf")
    plt.close(fig)

    for n, name in zip(ns, ("Twenty", "Fifty", "Eighty", "Hundred")):
        macros.add(f"OmegaPeak{name}", sci(float(cb.binom_exact(n, n // 2)), 4))
        macros.add(f"PPeak{name}", f"{th.prob(n, n // 2):.4f}")

    lim = cb.float_overflow_limits()
    macros.add("LimTotal", str(lim["total_states"]))
    macros.add("LimFact", str(lim["factorial"]))
    macros.add("LimCentral", str(lim["central_binomial"]))
    macros.add("FloatMax", sci(cb.FLOAT_MAX, 3))
    print(f"\nDouble-precision limits: {lim}")

    # Monte Carlo cross-check
    rng = np.random.default_rng(2026)
    n, trials = 100, 100_000
    counts = th.simulate_tosses(n, trials, rng)
    k = np.arange(n + 1)
    p_exact = th.prob(n, k)
    p_mc = counts / trials
    err = np.sqrt(counts) / trials  # Poisson counting uncertainty
    mask = counts > 0
    chi2 = float(np.sum((counts[mask] - trials * p_exact[mask]) ** 2 / (trials * p_exact[mask])))
    dof = int(mask.sum()) - 1
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    ax.errorbar(k[mask], p_mc[mask], yerr=err[mask], fmt="o", ms=2.5, capsize=1.5,
                label=f"Simulation, {trials:,} tosses")
    ax.plot(k, p_exact, "-", lw=1, label=r"Exact $\Omega(N,k)/2^N$")
    ax.set_xlim(25, 75)
    ax.set_xlabel("Number of heads $k$")
    ax.set_ylabel("Relative frequency")
    ax.legend(fontsize=8)
    fig.savefig(FIG / "fig_simulation.pdf")
    plt.close(fig)
    macros.add("MCtrials", f"{trials:,}".replace(",", r"\,"))
    macros.add("MCchi", f"{chi2:.1f}")
    macros.add("MCdof", str(dof))
    macros.add("MCmean", f"{(k * counts).sum() / trials:.3f}")
    macros.add("MCmeanErr", f"{np.sqrt(n / 4 / trials):.3f}")


