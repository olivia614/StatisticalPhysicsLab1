def sci(x: float, digits: int = 3) -> str:
    """LaTeX scientific notation, e.g. 1.23\\times10^{-5}."""
    if x == 0:
        return "0"
    if not math.isfinite(x):
        return r"\infty"
    exp = math.floor(math.log10(abs(x)))
    mant = x / 10**exp
    if abs(round(mant, digits - 1)) >= 10:  # abs: also for negative x (e.g. Delta S < 0)
        mant, exp = mant / 10, exp + 1
    if -2 <= exp <= 3:
        return f"{x:.{max(digits - 1 - exp, 0)}f}"
    return rf"{mant:.{digits - 1}f}\times10^{{{exp}}}"


def sci_log10(log10x: float, digits: int = 3) -> str:
    """Scientific notation for a number given by its log10 (no overflow)."""
    exp = math.floor(log10x)
    mant = 10 ** (log10x - exp)
    if round(mant, digits - 1) >= 10:
        mant, exp = mant / 10, exp + 1
    return rf"{mant:.{digits - 1}f}\times10^{{{exp}}}"


class MacroWriter:
    """Collects \\newcommand definitions for report/results.tex."""

    def __init__(self) -> None:
        self.lines: list[str] = [
            "% Auto-generated by main.py - do not edit by hand.",
        ]

    def add(self, name: str, value: str, math_mode: bool = True) -> None:
        body = rf"\ensuremath{{{value}}}" if math_mode else value
        self.lines.append(rf"\newcommand{{\{name}}}{{{body}}}")

    def write(self, path: Path) -> None:
        path.write_text("\n".join(self.lines) + "\n", encoding="utf-8")


