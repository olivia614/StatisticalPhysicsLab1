def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--nias", nargs="+", help="team NIAs (overrides team.json)")
    parser.add_argument("--team", type=Path, default=ROOT / "team.json")
    parser.add_argument("--benchmark", action="store_true", help="run the timing study")
    parser.add_argument("--verify-nmax", action="store_true",
                        help="with --benchmark, run the extrapolated N_max once")
    args = parser.parse_args()

    for d in (FIG, TAB, DATA):
        d.mkdir(parents=True, exist_ok=True)

    team = load_team(args.team)
    nias = args.nias or team_nias(team)
    if not nias:
        raise SystemExit("No NIAs given: fill in team.json or pass --nias.")
    missing = len(team.get("members", [])) - len(team_nias(team))
    if not args.nias and missing:
        print(f"WARNING: {missing} member(s) in team.json have no NIA yet; "
              f"N = 100 + M is computed from {len(nias)} NIA(s) only.")
    write_authors(team, REPORT / "authors.tex")

    macros = MacroWriter()
    part_enumeration(macros)

    bench_file = DATA / "benchmark.json"
    if args.benchmark:
        bench = run_benchmark(args.verify_nmax)
    elif bench_file.exists():
        bench = json.loads(bench_file.read_text(encoding="utf-8"))
    else:
        bench = None
    part_benchmark(macros, bench)

    part_distributions(macros)
    part_probabilities(macros, nias)
    part_thermo_limit(macros)
    macros.write(REPORT / "results.tex")
    print(f"\nWrote {REPORT / 'results.tex'} and figures in {FIG}")


if __name__ == "__main__":
    main()
