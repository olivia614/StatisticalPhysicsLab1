def part_probabilities(macros: MacroWriter, nias: list[str]) -> None:
    m = th.m_from_nias(nias)
    n = 100 + m
    h = th.half(n)
    digits = [int(x) % 100 for x in nias]
    print(f"\n=== N = 100 + M, NIA digits {digits}, harmonic mean {th.harmonic_mean(digits):.2f} "
          f"-> M = {m}, N = {n}, N/2 -> {h} ===")

    macros.add("NIAdigits", ", ".join(f"{d:02d}" for d in digits))
    macros.add("Mexact", f"{th.harmonic_mean(digits):.2f}")
    macros.add("Mval", str(m))
    macros.add("Nval", str(n))
    macros.add("Nhalf", str(h))
    macros.add("NisOdd", "odd" if n % 2 else "even", math_mode=False)
    macros.add(
        "HalfNote",
        rf"Since $N$ is odd, ``$N/2$ heads'' is taken as $\lfloor N/2\rfloor={h}$ "
        rf"(the macrostates $k={h}$ and $k={h + 1}$ are equally probable and tied for the maximum)."
        if n % 2
        else rf"Since $N$ is even, the equal split $N/2={h}$ is a valid macrostate.",
        math_mode=False,
    )
    macros.add("TotalStates", sci(2.0**n, 4))

    results = {}
    # Q1-Q4
    results["P30"] = th.prob(n, 30)
    results["Phalf"] = th.prob(n, h)
    results["Pten"] = th.prob_range(n, h - 10, h + 10)
    results["Ptwenty"] = th.prob_tails_range(n, h - 20, h + 20)
    macros.add("PthirtyHeads", sci(results["P30"]))
    macros.add("OmegaThirty", sci(float(cb.binom_exact(n, 30)), 4))
    macros.add("PhalfHeads", sci(results["Phalf"], 4))
    macros.add("OmegaHalf", sci(float(cb.binom_exact(n, h)), 4))
    macros.add("PtenHeads", sci(results["Pten"], 4))
    macros.add("PtwentyTails", sci(results["Ptwenty"], 6))
    macros.add("PtwentyTailsComp", sci(1 - results["Ptwenty"], 3))
    sigma = math.sqrt(n) / 2
    macros.add("SigmaN", f"{sigma:.1f}")
    macros.add("TenInSigma", f"{10 / sigma:.1f}")
    macros.add("TwentyInSigma", f"{20 / sigma:.1f}")
    macros.add("ThirtyInSigma", f"{(n / 2 - 30) / sigma:.1f}")
    macros.add("OutsideTenPct", f"{100 * (1 - results['Pten']):.1f}")

    # Q5-Q7 entropy differences, handout definition: Delta S_{k1 k2} = S(k1) - S(k2)
    for tag, (k1, k2) in {
        "A": (h + 25, h),
        "B": (h + 10, h),
        "C": (h, 20),
    }.items():
        ds = th.entropy_change(n, k1, k2)
        macros.add(f"dS{tag}from", str(k1))
        macros.add(f"dS{tag}to", str(k2))
        macros.add(f"dS{tag}", f"{ds:.3f}")
        macros.add(f"dS{tag}SI", sci(th.K_B * ds, 3))
        macros.add(f"dS{tag}ratio", sci(math.exp(ds), 3))
        macros.add(f"dS{tag}abs", f"{abs(ds):.1f}")
        results[f"dS{tag}"] = ds

    # Q8 waiting time for exactly 8 heads at one toss per second
    p8 = th.prob(n, 8)
    log10_wait = th.log10_expected_wait_seconds(n, 8)
    macros.add("PeightHeads", sci(p8))
    macros.add("WaitEightS", sci_log10(log10_wait))
    macros.add("WaitEightYears", sci_log10(log10_wait - math.log10(th.SECONDS_PER_YEAR)))
    macros.add("WaitEightUniverse",
               sci_log10(log10_wait - math.log10(th.AGE_OF_UNIVERSE_S)))
    results["wait8_log10_s"] = log10_wait

    # Q9 N/2 vs N/2 +- 10 heads (reading "M +- 10" of the handout as N/2 +- 10: with the
    # harmonic mean M is small, so M - 10 would be a negative number of heads)
    for tag, kk in (("Plus", h + 10), ("Minus", h - 10)):
        macros.add(f"M{tag}", str(kk))
        macros.add(f"P{tag}", sci(th.prob(n, kk)))
        macros.add(f"Ratio{tag}", sci(th.likelihood_ratio(n, h, kk)))
        results[f"ratio{tag}"] = th.likelihood_ratio(n, h, kk)

    for key, val in results.items():
        print(f"  {key:>14s} = {val:.6g}")

    # figure: distribution for N = 100 + M with the requested regions shaded
    k = np.arange(n + 1)
    p = th.prob(n, k)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.2, 3.0))
    ax1.plot(k, p, "k.-", ms=2.5, lw=0.7)
    sel = (k >= h - 10) & (k <= h + 10)
    ax1.fill_between(k[sel], p[sel], alpha=0.35, label=r"$N/2\pm10$ heads")
    for kk, lab in ((30, "30"), (h + 10, "$N/2+10$"), (h - 10, "$N/2-10$")):
        ax1.axvline(kk, ls=":", lw=0.8, color="tab:red")
        ax1.text(kk, p.max() * 0.9, lab, rotation=90, fontsize=7, ha="right", color="tab:red")
    ax1.set_xlabel("Number of heads $k$")
    ax1.set_ylabel("$P_k$")
    ax1.set_title(f"(a) $N={n}$", loc="left")
    ax1.legend(fontsize=7, loc="upper left")
    s = np.array([th.entropy(n, kk) for kk in k])
    ax2.plot(k, s, "k-", lw=1)
    for kk in (h + 25, h + 10, 20, 8):
        ax2.plot(kk, th.entropy(n, kk), "o", ms=4)
        ax2.annotate(str(kk), (kk, th.entropy(n, kk)), fontsize=7,
                     textcoords="offset points", xytext=(3, -8))
    ax2.set_xlabel("Number of heads $k$")
    ax2.set_ylabel(r"$S/k_B=\ln\Omega(N,k)$")
    ax2.set_title("(b)", loc="left")
    fig.tight_layout()
    fig.savefig(FIG / "fig_probabilities.pdf")
    plt.close(fig)


