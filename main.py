def part_thermo_limit(macros: MacroWriter) -> None:
    big = 1e23
    macros.add("TLwidth", sci(th.relative_width(big), 3))
    macros.add("TLsigma", sci(math.sqrt(big) / 2, 3))
    macros.add("TLPhalf", sci_log10(-0.5 * math.log10(math.pi * big / 2)))
    # macroscopic deviation x = 0.501 vs 0.5
    x = 0.501
    log10_ratio = th.log10_prob_fraction(big, x) - th.log10_prob_fraction(big, 0.5)
    ds_kb = log10_ratio * math.log(10)
    macros.add("TLlogRatio", sci(log10_ratio, 3))
    macros.add("TLdSkB", sci(abs(ds_kb), 3))  # magnitude |Delta S|
    macros.add("TLdSSI", sci(th.K_B * abs(ds_kb), 3))
    # probability that |k/N - 1/2| > 1e-10 (Gaussian tail, two-sided)
    eps = 1e-10
    z = 2 * eps * math.sqrt(big)
    log10_tail = (math.log(2) + float(log_ndtr(-z))) / math.log(10)
    macros.add("TLeps", sci(eps, 1))
    macros.add("TLz", f"{z:.0f}")
    macros.add("TLtail", sci_log10(log10_tail))
    # same Q8 question at N = 1e23: probability of exactly 8 heads
    log10_p8 = (float(cb.log_binom(big, 8)) - big * math.log(2)) / math.log(10)
    # the exponent itself is ~1e22, so only its leading digits are meaningful
    macros.add("TLPeight", rf"10^{{{sci(log10_p8, 3)}}}")

    # narrowing of the distribution in k/N as N grows
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    for n in (1e2, 1e4, 1e6, 1e8):
        # dense grid within +-8 sigma of the peak so narrow peaks are resolved
        half_w = 8 * th.relative_width(n) / 2
        x_grid = np.concatenate(
            ([0.3], np.linspace(0.5 - half_w, 0.5 + half_w, 2001), [0.7])
        )
        x_grid = np.clip(x_grid, 0.3, 0.7)
        density = th.gaussian_approx(n, x_grid * n)
        e = int(math.log10(n))
        ax.plot(x_grid, density / density.max(), lw=1,
                label=rf"$N=10^{{{e}}}$, $\sigma/\mu=10^{{{-e // 2}}}$")
    ax.set_xlabel("Fraction of heads $k/N$")
    ax.set_ylabel(r"$P(k/N)\,/\,P_{\max}$")
    ax.legend(fontsize=7)
    fig.savefig(FIG / "fig_thermo_limit.pdf")
    plt.close(fig)

    # accuracy of Stirling / Gaussian at N = 100
    n = 100
    rel = abs(th.gaussian_approx(n, 50) / th.prob(n, 50) - 1)
    macros.add("GaussErrHundred", sci(rel * 100, 2))


