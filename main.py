def run_benchmark(verify_nmax: bool) -> dict:
    workers = os.cpu_count() or 1
    print(f"\n=== Benchmark (workers = {workers}) ===")
    data: dict = {"workers": workers, "time_limit_s": TIME_LIMIT_S}
    data["generator"] = ms.benchmark(list(range(16, 27)), method="generator", repeats=3)
    for r in data["generator"]:
        print(f"generator  N={r['n']:2d}  t={r['t_mean']:.3f}+-{r['t_std']:.3f} s")
    data["vectorized"] = ms.benchmark(
        list(range(26, 36)), method="vectorized", repeats=3, workers=workers
    )
    for r in data["vectorized"]:
        print(f"vectorized N={r['n']:2d}  t={r['t_mean']:.3f}+-{r['t_std']:.3f} s")

    if verify_nmax:
        # Run the extrapolated N_max; step down until it fits in the time limit
        n_try = int(math.floor(_fits(data)["vectorized"]["n_limit"]))
        # safety cap: never more than 3 coins (8x) beyond the largest timed N
        n_try = min(n_try, data["vectorized"][-1]["n"] + 3)
        data["verified_runs"] = []
        while n_try > 0:
            print(f"Verifying N = {n_try} ...")
            t0 = time.perf_counter()
            counts = ms.count_macrostates_vectorized(n_try, workers=workers)
            elapsed = time.perf_counter() - t0
            ok = int(counts.sum()) == 2**n_try and int(
                counts[n_try // 2]
            ) == math.comb(n_try, n_try // 2)
            print(f"N={n_try}: {elapsed:.1f} s, histogram correct: {ok}")
            data["verified_runs"].append({"n": n_try, "t": elapsed, "correct": ok})
            if elapsed <= TIME_LIMIT_S:
                data["verified"] = data["verified_runs"][-1]
                break
            n_try -= 1

    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "benchmark.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    return data


def _fits(data: dict) -> dict:
    fits = {}
    for method in ("generator", "vectorized"):
        rec = data[method]
        n = np.array([r["n"] for r in rec])
        t = np.array([r["t_mean"] for r in rec])
        # asymptotic O(2^N) regime only: small-N runs are overhead-dominated.
        # The free slope b is a consistency check; N_max uses t = c 2^N (robust).
        _, a, b = ms.extrapolate_n_max(n[-4:], t[-4:], data["time_limit_s"])
        n_lim, c = ms.per_state_cost(n[-4:], t[-4:], data["time_limit_s"])
        fits[method] = {"n_limit": n_lim, "c": c, "a": a, "b": b}
    return fits


def part_benchmark(macros: MacroWriter, data: dict | None) -> None:
    if data is None:
        for name in ("NmaxGen", "NmaxVec", "SlopeGen", "SlopeVec", "CostGen", "CostVec", "Workers",
                     "NverifyVal", "TverifyVal"):
            macros.add(name, r"\text{[run main.py --benchmark]}")
        (TAB / "benchmark.tex").write_text(
            r"\multicolumn{5}{c}{Run \texttt{python main.py --benchmark}} \\" + "\n",
            encoding="utf-8",
        )
        return

    fits = _fits(data)
    macros.add("Workers", str(data["workers"]))
    macros.add("NmaxGen", f"{fits['generator']['n_limit']:.1f}")
    macros.add("NmaxVec", f"{fits['vectorized']['n_limit']:.1f}")
    macros.add("SlopeGen", f"{fits['generator']['b']:.3f}")
    macros.add("SlopeVec", f"{fits['vectorized']['b']:.3f}")
    macros.add("CostGen", f"{fits['generator']['c'] * 1e9:.1f}")
    macros.add("CostVec", f"{fits['vectorized']['c'] * 1e9:.2f}")
    ver = data.get("verified")
    macros.add("NverifyVal", str(ver["n"]) if ver else r"\text{n/a}")
    macros.add("TverifyVal", f"{ver['t']:.0f}" if ver else r"\text{n/a}")

    rows = []
    gen = {r["n"]: r for r in data["generator"]}
    vec = {r["n"]: r for r in data["vectorized"]}
    for n in sorted(set(gen) | set(vec)):
        if n % 2:
            continue
        def cell(r):
            return (rf"${r['t_mean']:.3g} \pm {r['t_std']:.2g}$" if r else "---")
        def mem(r):
            return f"{max(r['mem_peak_mb'], 0.01):.2f}" if r else "---"
        rows.append(
            rf"{n} & ${sci(2.0**n)}$ & {cell(gen.get(n))} & {cell(vec.get(n))} & "
            rf"{mem(gen.get(n))} / {mem(vec.get(n))} \\"
        )
    for v in data.get("verified_runs", []):
        rows.append(
            rf"{v['n']} & ${sci(2.0**v['n'])}$ & --- & ${v['t']:.0f}$ (1 run) & --- \\"
        )
    (TAB / "benchmark.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")

    # figure
    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    n_grid = np.linspace(15, 40, 100)
    for method, marker, label in (
        ("generator", "o", "Python generator (1 core)"),
        ("vectorized", "s", f"Chunked NumPy ({data['workers']} processes)"),
    ):
        rec = data[method]
        n = np.array([r["n"] for r in rec])
        t = np.array([r["t_mean"] for r in rec])
        s = np.array([r["t_std"] for r in rec])
        line = ax.errorbar(n, t, yerr=s, fmt=marker, ms=4, capsize=2, label=label)
        f = fits[method]
        ax.plot(n_grid, f["c"] * 2.0**n_grid, "--", lw=0.8,
                color=line[0].get_color())
    for i, v in enumerate(data.get("verified_runs", [])):
        ax.plot(v["n"], v["t"], "*", ms=10, color="k",
                label="Single verification run" if i == 0 else None)
    ax.axhline(TIME_LIMIT_S, color="r", lw=1)
    ax.text(15.5, TIME_LIMIT_S * 1.3, "5 min limit", color="r")
    ax.set_yscale("log")
    ax.set_xlim(15, 40)
    ax.set_xlabel("Number of coins $N$")
    ax.set_ylabel("Wall-clock time (s)")
    ax.legend(fontsize=8, loc="lower right")
    fig.savefig(FIG / "fig_benchmark.pdf")
    plt.close(fig)


